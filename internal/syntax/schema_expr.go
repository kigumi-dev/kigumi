package syntax

var (
	blk     = set(Block)
	elseSet = set(Block, IfExpr, IfLetExpr)
)

var exprSchema = []kindSchema{
	{Ident, "Ident", layLeaf, "Name", nil},
	{DefaultArg, "DefaultArg", layLeaf, "Call", nil},
	{IntLit, "IntLit", layLeaf, "Lit", nil},
	{FloatLit, "FloatLit", layLeaf, "Lit", nil},
	{CharLit, "CharLit", layLeaf, "Lit", nil},
	{BoolLit, "BoolLit", layLeaf, "Lit", nil},
	{ByteStringLit, "ByteStringLit", layLeaf, "Lit", nil},
	{StringLit, "StringLit", layL, "Lit", []slot{olst("Interps", exprSet)}},
	{ShellLit, "ShellLit", layTokR, "Dollar", []slot{tk("Str"), ch("Plan", set(ShellPlan))}},
	{Paren, "Paren", layL, "Open", []slot{ch("Inner", exprSet.or(typeSet))}},
	{Unary, "Unary", layL, "Op", []slot{ch("Operand", exprSet)}},
	{Binary, "Binary", layLR, "Op", []slot{ch("Left", exprSet), ch("Right", exprSet)}},
	{IsExpr, "Is", layLR, "Op", []slot{ch("Left", exprSet), ch("Pattern", patSet)}},
	{CallExpr, "Call", layLR, "Head", []slot{ch("Callee", exprSet), lst("Args", argSet)}},
	{WsCallExpr, "WsCall", layLR, "Head", []slot{ch("Callee", exprSet), lst("Args", exprSet)}},
	{BracketExpr, "Bracket", layLR, "Open", []slot{ch("Base", exprSet), lst("Args", exprOrType)}},
	{MemberExpr, "Member", layL, "Member", []slot{ch("Base", exprSet)}},
	{OptMemberExpr, "OptMember", layL, "Member", []slot{ch("Base", exprSet)}},
	{TryExpr, "Try", layL, "Op", []slot{ch("Operand", exprSet)}},
	{RecordLit, "RecordLit", layLR, "Open", []slot{ch("Head", exprSet), lst("Fields", set(FieldInit, Spread))}},
	{FieldInit, "FieldInit", layL, "Name", []slot{ch("Value", exprSet)}},
	{Spread, "Spread", layL, "Dots", []slot{ch("Value", exprSet)}},
	{NamedArg, "NamedArg", layL, "Name", []slot{ch("Value", exprSet)}},
	{TupleLit, "TupleLit", layList, "Open", []slot{items(exprSet)}},
	{UnitLit, "UnitLit", layLeaf, "Open", nil},
	{Lambda, "Lambda", layLR, "Open", []slot{lst("Params", set(Param)), ch("Body", exprSet)}},
	{Block, "Block", layList, "Open", []slot{items(stmtSet)}},
	{IfExpr, "If", layRec, "Kw", []slot{ch("Cond", exprSet), ch("Then", blk), och("Else", elseSet)}},
	{IfLetExpr, "IfLet", layRec, "Kw", []slot{
		num("Flags"), ch("Pattern", patSet), ch("Init", exprSet), och("Guard", exprSet),
		ch("Then", blk), och("Else", elseSet),
	}},
	{MatchExpr, "Match", layLR, "Kw", []slot{ch("Scrutinee", exprSet), lst("Arms", set(MatchArm))}},
	{MatchArm, "Arm", layRec, "Head", []slot{ch("Pattern", patSet), och("Guard", exprSet), ch("Body", exprSet)}},
	{ForExpr, "For", layRec, "Kw", []slot{och("Pattern", patSet), och("Head", exprSet), ch("Body", blk)}},
	{ReturnExpr, "Return", layL, "Kw", []slot{och("Value", exprSet)}},
	{FailExpr, "Fail", layL, "Kw", []slot{och("Value", exprSet)}},
	{BreakExpr, "Break", layL, "Kw", []slot{och("Value", exprSet)}},
	{ContinueExpr, "Continue", layLeaf, "Kw", nil},
	{AwaitExpr, "Await", layL, "Kw", []slot{ch("Operand", exprSet)}},
	{ComptimeExpr, "Comptime", layL, "Kw", []slot{ch("Body", exprSet)}},
	{UnsafeExpr, "Unsafe", layL, "Kw", []slot{ch("Body", blk)}},
	{AllocatorExpr, "Allocator", layLR, "Kw", []slot{ch("Scope", exprSet), ch("Body", blk)}},
	{ContextExpr, "Context", layLR, "Kw", []slot{lst("Provides", exprSet), ch("Body", blk)}},
	{ContractExpr, "Contract", layFlagR, "Head", []slot{num("Mods"), ch("Body", blk)}},
	{BorrowExpr, "Borrow", layFlagR, "Op", []slot{num("Flags"), ch("Operand", exprSet)}},
	{MoveExpr, "Move", layL, "Kw", []slot{ch("Operand", exprSet)}},
	{AsmExpr, "Asm", layL, "Kw", []slot{lst("Lines", set(AsmTemplate, AsmOperand, AsmClobber, AsmOptions))}},
	{AsmTemplate, "AsmTemplate", layL, "Head", []slot{ch("Text", set(StringLit))}},
	{AsmOperand, "AsmOperand", layRec, "", []slot{otk("Label"), tk("Dir"), otk("Reg"), och("Expr", exprSet)}},
	{AsmClobber, "AsmClobber", layL, "Kw", []slot{lst("Names", set(Ident, AsmAbi))}},
	{AsmOptions, "AsmOptions", layL, "Kw", []slot{lst("Names", set(Ident))}},
	{AsmAbi, "AsmAbi", layLeaf, "Name", nil},
}

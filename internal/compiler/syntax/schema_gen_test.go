package syntax

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const genHeader = "// Code generated by TestViewsFresh (UPDATE=1 go test ./internal/compiler/syntax -run TestViewsFresh); DO NOT EDIT.\n\npackage syntax\n\n"

const genChunkLines = 170

func slotPos(l layout, i int) string {
	switch l {
	case layL, layLR, layFlagR, layTokR, laySpan:
		if i == 0 {
			return "v.lhs()"
		}
		return "v.rhs()"
	}
	return fmt.Sprintf("v.rec(%d)", i)
}

func viewFor(s kindSet) (typ, wrap string) {
	if s.count() == 1 {
		k := s.only()
		for _, ks := range schema {
			if ks.kind == k {
				return ks.view + "View", ".As" + ks.view + "()"
			}
		}
	}
	for _, c := range []struct {
		set  kindSet
		name string
	}{{exprSet, "Expr"}, {typeSet, "TypeExpr"}, {patSet, "Pattern"}, {stmtSet, "Stmt"}, {declSet, "Decl"}} {
		if s.subsetOf(c.set) {
			return c.name + "View", ".As" + c.name + "()"
		}
	}
	return "View", ""
}

func genKind(ks kindSchema) string {
	var b strings.Builder
	name := ks.view
	typ := name + "View"
	embed, ctor := "View", "v"
	if ks.layout == layList {
		embed, ctor = "ListView", "ListView{v}"
	}
	if ks.kind != List && ks.kind != Path {
		fmt.Fprintf(&b, "type %s struct{ %s }\n\n", typ, embed)
		fmt.Fprintf(&b, "func (v View) As%s() %s { return %s{%s} }\n", name, typ, typ, ctor)
	}
	if ks.tok != "" {
		fmt.Fprintf(&b, "func (v %s) %s() TokenRef { return v.Tok() }\n", typ, ks.tok)
	}
	for i, s := range ks.slots {
		pos := slotPos(ks.layout, i)
		switch s.role {
		case roleChild:
			rt, wrap := viewFor(s.kinds)
			if rt == "View" {
				fmt.Fprintf(&b, "func (v %s) %s() View { return v.at(%s) }\n", typ, s.name, pos)
			} else {
				fmt.Fprintf(&b, "func (v %s) %s() %s { return v.at(%s)%s }\n", typ, s.name, rt, pos, wrap)
			}
		case roleList:
			fmt.Fprintf(&b, "func (v %s) %s() ListView { return ListView{v.at(%s)} }\n", typ, s.name, pos)
		case roleTok:
			fmt.Fprintf(&b, "func (v %s) %s() TokenRef { return v.tokRef(%s) }\n", typ, s.name, pos)
		case roleInt:
			fmt.Fprintf(&b, "func (v %s) %s() uint32 { return %s }\n", typ, s.name, pos)
		}
	}
	b.WriteString("\n")
	return b.String()
}

func genViews(t *testing.T) map[string]string {
	t.Helper()
	files := map[string]string{}
	var cur strings.Builder
	n := 0
	flush := func() {
		if cur.Len() == 0 {
			return
		}
		n++
		src, err := format.Source([]byte(genHeader + cur.String()))
		if err != nil {
			t.Fatalf("generated chunk %d does not format: %v\n%s", n, err, cur.String())
		}
		files[fmt.Sprintf("views_gen_%02d.go", n)] = string(src)
		cur.Reset()
	}
	for _, ks := range schema {
		g := genKind(ks)
		if strings.Count(cur.String(), "\n")+strings.Count(g, "\n") > genChunkLines {
			flush()
		}
		cur.WriteString(g)
	}
	flush()
	return files
}

func TestViewsFresh(t *testing.T) {
	want := genViews(t)
	existing, _ := filepath.Glob("views_gen_*.go")
	if os.Getenv("UPDATE") != "" {
		for _, f := range existing {
			if _, keep := want[f]; !keep {
				os.Remove(f)
			}
		}
		for f, src := range want {
			if err := os.WriteFile(f, []byte(src), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		return
	}
	for f, src := range want {
		got, err := os.ReadFile(f)
		if err != nil || !bytes.Equal(got, []byte(src)) {
			t.Errorf("%s is stale; run UPDATE=1 go test ./internal/compiler/syntax -run TestViewsFresh", f)
		}
	}
	for _, f := range existing {
		if _, ok := want[f]; !ok {
			t.Errorf("%s is no longer generated; run UPDATE=1 go test ./internal/compiler/syntax -run TestViewsFresh", f)
		}
	}
}

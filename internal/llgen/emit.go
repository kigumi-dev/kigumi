// Package llgen emits LLVM IR text from MIR.
package llgen

import (
	"fmt"
	"maps"
	"slices"
	"strings"

	"kigumi/internal/mir"
	"kigumi/internal/sem"
)

type emitter struct {
	p            *mir.Program
	entryAllocas []string
	hoisting     bool
	freestanding bool
	reachable    *mir.Reachability
	r            *sem.Result
	out          strings.Builder
	strs         map[string]string
	strList      []string
	descs        map[sem.EntityID]string
	vdescs       map[sem.EntityID]string
	tables       strings.Builder
	foreign      map[string]string
	helpers      strings.Builder
	cio          map[string]bool
	ntypes       int
	tmp          int
	stdDrops     map[sem.EntityID]bool
	shim         *cshim
	modAsm       strings.Builder
	symPrefix    string
	scalar       map[mir.LocalID]scalarInfo
	fnItems      map[string]fnItem
	stdBinds     []stdBind
	stdBindOf    map[string]string
	constVals    map[string]constVal
	constIndex   map[string]int
	constOrder   []string
	constKey     map[mir.LocalID]string
	constOwned   map[mir.LocalID]bool
	aggs         map[sem.TypeID]*aggInfo
	aggOrder     []sem.TypeID
	aggDone      map[sem.TypeID]bool
	direct       map[mir.LocalID]*aggInfo
	boxTmp       map[mir.LocalID]bool
	sigs         map[*mir.Func]*aggSig
	sig          *aggSig
}

func EmitProgram(p *mir.Program, opts EmitOptions) Output {
	e := &emitter{p: p, r: p.R, strs: map[string]string{}, descs: map[sem.EntityID]string{}, vdescs: map[sem.EntityID]string{}, foreign: map[string]string{}, stdDrops: map[sem.EntityID]bool{}, cio: map[string]bool{}, fnItems: map[string]fnItem{}, stdBindOf: map[string]string{}, constVals: map[string]constVal{}, constIndex: map[string]int{}, aggs: map[sem.TypeID]*aggInfo{}, aggDone: map[sem.TypeID]bool{}, sigs: map[*mir.Func]*aggSig{}, freestanding: opts.Freestanding, symPrefix: opts.SymbolPrefix, reachable: opts.Reachable, shim: newCshim()}
	var body strings.Builder
	for _, f := range p.Funcs {
		if e.reachable != nil && !e.reachable.Keep(f.Ent) {
			continue
		}
		if e.r.Entity(f.Ent).Kind == sem.EntFn && e.r.Fn(f.Ent).Naked {
			e.nakedFn(f)
			continue
		}
		if f.Async {
			body.WriteString(e.asyncFunction(f))
			e.helpers.WriteString(e.asyncDesc(f))
			continue
		}
		body.WriteString(e.function(f))
		body.WriteString(e.adapter(f))
		if e.r.Entity(f.Ent).Kind == sem.EntFn && e.r.Fn(f.Ent).Abi == "" {
			body.WriteString(e.bindAdapter(f))
		}
		if e.r.Entity(f.Ent).Kind == sem.EntFn && e.r.Fn(f.Ent).Recv != sem.RecvNone {
			body.WriteString(e.methodAdapter(f))
		}
		if e.r.Entity(f.Ent).Kind == sem.EntFn && e.r.Fn(f.Ent).Export != "" {
			switch {
			case e.r.Fn(f.Ent).Export == "interrupt":
				body.WriteString(e.exportInterruptWrapper(f))
			case e.byValue(e.r.Fn(f.Ent).Sig):
				body.WriteString(e.exportByval(f))
			default:
				body.WriteString(e.exportWrapper(f))
			}
		}
	}
	// Both add foreign declarations before those are written, and a static's
	// initializer adds literal pool and immortal slots that data() emits.
	globalDecls, globalInit := e.staticGlobals()
	data := e.data()
	e.out.WriteString(header)
	e.out.WriteString(e.aggTypes())
	e.out.WriteString(e.modAsm.String())
	e.out.WriteString(externs)
	for _, name := range slices.Sorted(maps.Keys(e.foreign)) {
		e.out.WriteString(e.foreign[name] + "\n")
	}
	e.out.WriteString(globalDecls)
	e.out.WriteString(data)
	e.out.WriteString(body.String())
	e.out.WriteString(globalInit)
	e.out.WriteString(e.helpers.String())
	e.out.WriteString(e.initImmortals())
	e.out.WriteString(e.mainWrapper())
	var caps []string
	if opts.Reachable != nil {
		caps = mir.CapabilityMacros(opts.Reachable.Ops)
	}
	return Output{IR: e.out.String(), CShim: e.shim.text(), Threads: mir.UsesThreads(p), Capabilities: caps}
}

const header = `; generated by kigumi
%rt_type = type { ptr, i32, i32, ptr, i32, ptr, ptr, i64 }
%rt_variant = type { ptr, ptr, i32, i32, [64 x i8] }
@kg_cancel_marker = external global i8

`

func (e *emitter) newTmp() string {
	e.tmp++
	return fmt.Sprintf("%%v%d", e.tmp)
}

func (e *emitter) function(f *mir.Func) string {
	var sb strings.Builder
	e.tmp = 0
	e.sig = e.directSig(f)
	e.direct = e.classifyDirect(f)
	e.boxTmp = boxTemps(f)
	e.scalar = e.classifyScalars(f)
	e.constOwned = map[mir.LocalID]bool{}
	e.constKey = e.constLocals(f)
	sb.WriteString(e.sigHeader(f, e.sig))
	if e.r.Entity(f.Ent).Kind == sem.EntFn {
		if name := e.r.FnSectionOf(f.Ent); name != "" {
			fmt.Fprintf(&sb, " section %q", name)
		}
	}
	sb.WriteString(" {\nentry:\n")
	for i := range f.Locals {
		if a, ok := e.direct[mir.LocalID(i)]; ok {
			fmt.Fprintf(&sb, "  %%l%d = alloca %s\n", i, a.Name)
			fmt.Fprintf(&sb, "  store %s zeroinitializer, ptr %%l%d\n", a.Name, i)
			continue
		}
		if info, ok := e.scalar[mir.LocalID(i)]; ok {
			fmt.Fprintf(&sb, "  %%l%d = alloca %s\n", i, info.Ty)
			fmt.Fprintf(&sb, "  store %s %s, ptr %%l%d\n", info.Ty, zeroOf(info.Ty), i)
			continue
		}
		fmt.Fprintf(&sb, "  %%l%d = alloca ptr\n", i)
		fmt.Fprintf(&sb, "  store ptr null, ptr %%l%d\n", i)
	}
	var body strings.Builder
	e.entryAllocas, e.hoisting = nil, true
	for bid, blk := range f.Blocks {
		fmt.Fprintf(&body, "b%d:\n", bid)
		for _, in := range blk.Insts {
			e.inst(&body, f, in)
		}
		e.term(&body, blk.Term)
	}
	e.hoisting = false
	for _, a := range e.entryAllocas {
		sb.WriteString(a)
	}
	// Parameters arrive owned or borrowed; either way, store as is.
	e.storeParams(&sb, f, e.sig)
	sb.WriteString("  br label %b0\n")
	sb.WriteString(body.String())
	sb.WriteString("}\n\n")
	return sb.String()
}

func (e *emitter) load(sb *strings.Builder, l mir.LocalID) string {
	t := e.newTmp()
	fmt.Fprintf(sb, "  %s = load ptr, ptr %%l%d\n", t, l)
	return t
}

func (e *emitter) store(sb *strings.Builder, l mir.LocalID, v string) {
	fmt.Fprintf(sb, "  store ptr %s, ptr %%l%d\n", v, l)
}

// Diagnostic is one machine-readable problem an emitter reports instead of
// silently dropping a declaration: Code is stable for a consumer to switch
// on, Message is for a human, and Source is the declaration's stable ID.
type Diagnostic struct {
	Code     string `json:"code"`
	Severity string `json:"severity"`
	Message  string `json:"message"`
	Source   string `json:"source,omitempty"`
}

// C-header diagnostic codes; a consumer matches these exact strings.
const (
	DiagCHeaderUnsupportedType = "header-unsupported-type"
	DiagCHeaderUnsupportedDecl = "header-unsupported-declaration"
	DiagCHeaderNotCABI         = "header-not-c-abi"
	DiagCHeaderDuplicateName   = "header-duplicate-name"
	DiagCHeaderCycle           = "header-cycle"
	DiagCHeaderEmptyRecord     = "header-empty-record"
)

// CHeaderOptions configures EmitCHeader.
type CHeaderOptions struct {
	// Guard is the include guard macro; derived from the module's first scope
	// package when empty.
	Guard string
}

// CHeaderDecl records one declaration the header emitted, in header order.
type CHeaderDecl struct {
	ID     string `json:"id"`
	Kind   string `json:"kind"`
	Symbol string `json:"symbol"`
}

// CHeader is a rendered C header plus what it emitted and what it left out;
// byte-identical input renders byte-identical output.
type CHeader struct {
	Guard        string        `json:"guard"`
	Text         string        `json:"text"`
	Declarations []CHeaderDecl `json:"declarations"`
	Diagnostics  []Diagnostic  `json:"diagnostics"`
}

// EmitCHeader renders the C declarations of mod's ABI boundary: opaque
// extern types, layout(C) records and extern/export(C) functions. A
// declaration with no C representation is reported in Diagnostics and left
// out, the way a C-header importer lists what it skipped.
func EmitCHeader(mod *Module, opt CHeaderOptions) CHeader {
	w := &headerWriter{byID: map[string]*Declaration{}}
	for _, d := range mod.Declarations {
		w.byID[d.ID] = d
	}
	guard := opt.Guard
	if guard == "" {
		guard = defaultGuard(mod)
	}

	var opaques, records, fns []*Declaration
	for _, d := range mod.Declarations {
		switch {
		case d.Kind == KindType && d.Opaque:
			opaques = append(opaques, d)
		case d.Kind == KindType && d.Layout != "":
			records = append(records, d)
		case d.Kind == KindFn && d.ABI != nil:
			fns = append(fns, d)
		case d.ABI != nil:
			w.report(DiagCHeaderUnsupportedDecl, d, "a %s declaration cannot cross the C ABI", d.Kind)
		}
	}

	sort.SliceStable(opaques, func(i, j int) bool { return opaques[i].Name < opaques[j].Name })
	sort.SliceStable(fns, func(i, j int) bool {
		if si, sj := w.symbolOf(fns[i]), w.symbolOf(fns[j]); si != sj {
			return si < sj
		}
		return fns[i].ID < fns[j].ID
	})

	ordered := w.orderRecords(records)

	var decls []CHeaderDecl
	var body []string
	seenType := map[string]bool{}
	for _, d := range opaques {
		if !w.claimName(seenType, d) {
			continue
		}
		body = append(body, w.opaqueText(d))
		decls = append(decls, CHeaderDecl{ID: d.ID, Kind: "opaque", Symbol: d.Name})
	}
	for _, d := range ordered {
		if !w.claimName(seenType, d) {
			continue
		}
		text, ok := w.structText(d)
		if !ok {
			continue
		}
		body = append(body, text)
		decls = append(decls, CHeaderDecl{ID: d.ID, Kind: "struct", Symbol: d.Name})
	}
	seenSymbol := map[string]string{}
	for _, d := range fns {
		text, symbol, ok := w.fnText(d)
		if !ok {
			continue
		}
		if prev, dup := seenSymbol[symbol]; dup {
			if prev != text {
				w.report(DiagCHeaderDuplicateName, d, "the C symbol `%s` is already declared by another prototype", symbol)
			}
			continue
		}
		seenSymbol[symbol] = text
		body = append(body, text)
		decls = append(decls, CHeaderDecl{ID: d.ID, Kind: "fn", Symbol: symbol})
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "/* Generated by `kigumi emit-c-header`; do not edit.\n * schema-version: %s\n * canonical-abi-version: %s\n */\n",
		schemaVersion(mod.Envelope), version.CanonicalABIVersion)
	fmt.Fprintf(&sb, "#ifndef %s\n#define %s\n", guard, guard)
	includes := w.includes()
	if len(includes) != 0 {
		sb.WriteString("\n")
		for _, inc := range includes {
			fmt.Fprintf(&sb, "#include <%s>\n", inc)
		}
	}
	sb.WriteString("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
	for _, text := range body {
		sb.WriteString("\n")
		sb.WriteString(text)
		sb.WriteString("\n")
	}
	sb.WriteString("\n#ifdef __cplusplus\n}\n#endif\n")
	fmt.Fprintf(&sb, "\n#endif /* %s */\n", guard)

	for _, d := range w.diags {
		sb.WriteString("\n/* ")
		sb.WriteString(d.Severity)
		sb.WriteString("[")
		sb.WriteString(d.Code)
		sb.WriteString("]: ")
		sb.WriteString(d.Message)
		if d.Source != "" {
			sb.WriteString(" (")
			sb.WriteString(d.Source)
			sb.WriteString(")")
		}
		sb.WriteString(" */")
	}
	return CHeader{Guard: guard, Text: sb.String(), Declarations: decls, Diagnostics: w.diags}
}

type headerWriter struct {
	byID  map[string]*Declaration
	diags []Diagnostic
	// usedBool/usedInt/usedSize track which headers the emitted declarations need.
	usedBool, usedInt, usedSize bool
}

func (w *headerWriter) report(code string, d *Declaration, format string, args ...any) {
	w.diags = append(w.diags, Diagnostic{Code: code, Severity: "warning", Message: fmt.Sprintf(format, args...), Source: d.ID})
}

func (w *headerWriter) includes() []string {
	var out []string
	if w.usedBool {
		out = append(out, "stdbool.h")
	}
	if w.usedSize {
		out = append(out, "stddef.h")
	}
	if w.usedInt {
		out = append(out, "stdint.h")
	}
	return out
}

func (w *headerWriter) symbolOf(d *Declaration) string {
	if d.ABI != nil && d.ABI.Symbol != "" {
		return d.ABI.Symbol
	}
	return d.Name
}

// claimName reserves a C type name for d, reporting a second declaration that
// wants the same one rather than emitting two conflicting structs.
func (w *headerWriter) claimName(seen map[string]bool, d *Declaration) bool {
	if !isCIdent(d.Name) {
		w.report(DiagCHeaderDuplicateName, d, "`%s` is not a C identifier", d.Name)
		return false
	}
	if seen[d.Name] {
		w.report(DiagCHeaderDuplicateName, d, "the C type name `%s` is already declared by another type", d.Name)
		return false
	}
	seen[d.Name] = true
	return true
}

func (w *headerWriter) opaqueText(d *Declaration) string {
	return fmt.Sprintf("/* %s */\ntypedef struct %s %s;", originComment(d), d.Name, d.Name)
}

func (w *headerWriter) structText(d *Declaration) (string, bool) {
	if len(d.Fields) == 0 {
		w.report(DiagCHeaderEmptyRecord, d, "an empty layout(C) record has no C representation (C has no zero-size struct)")
		return "", false
	}
	var fields []string
	for i, f := range d.Fields {
		name := f.Name
		if !isCIdent(name) || cKeyword(name) {
			name = "f" + strconv.Itoa(i)
		}
		text, ok := w.declType(f.Type, name, 0)
		if !ok {
			w.report(DiagCHeaderUnsupportedType, d, "field `%s` has type `%s`, which has no C representation", f.Name, displayOf(f.Type))
			return "", false
		}
		fields = append(fields, "    "+text+";")
	}
	var attrs []string
	if d.Layout == "packed" {
		attrs = append(attrs, "packed")
	}
	if d.Align > 0 {
		attrs = append(attrs, fmt.Sprintf("aligned(%d)", d.Align))
	}
	attr := ""
	if len(attrs) != 0 {
		attr = " __attribute__((" + strings.Join(attrs, ", ") + "))"
	}
	return fmt.Sprintf("/* %s */\nstruct %s {\n%s\n}%s;\ntypedef struct %s %s;",
		originComment(d), d.Name, strings.Join(fields, "\n"), attr, d.Name, d.Name), true
}

func (w *headerWriter) fnText(d *Declaration) (string, string, bool) {
	if d.ABI.Name != "C" {
		w.report(DiagCHeaderNotCABI, d, "`%s(%s)` has no C declaration", d.ABI.Block, d.ABI.Name)
		return "", "", false
	}
	symbol := w.symbolOf(d)
	if !isCIdent(symbol) {
		w.report(DiagCHeaderDuplicateName, d, "`%s` is not a C identifier", symbol)
		return "", "", false
	}
	ret := "void"
	if d.Return != nil {
		text, ok := w.typeName(d.Return, 0)
		if !ok {
			w.report(DiagCHeaderUnsupportedType, d, "the return type `%s` has no C representation", displayOf(d.Return))
			return "", "", false
		}
		ret = text
	}
	var params []string
	for i, p := range d.Params {
		name := p.Name
		if !isCIdent(name) || cKeyword(name) {
			name = "arg" + strconv.Itoa(i)
		}
		text, ok := w.declType(p.Type, name, 0)
		if !ok {
			w.report(DiagCHeaderUnsupportedType, d, "parameter `%s` has type `%s`, which has no C representation", p.Name, displayOf(p.Type))
			return "", "", false
		}
		params = append(params, text)
	}
	if d.ABI.Variadic {
		params = append(params, "...")
	}
	list := "(void)"
	if len(params) != 0 {
		list = "(" + strings.Join(params, ", ") + ")"
	}
	return fmt.Sprintf("/* %s */\n%s %s%s;", originComment(d), ret, symbol, list), symbol, true
}

// orderRecords sorts records so a by-value field's struct is complete before
// the struct holding it, reporting a by-value cycle instead of emitting an
// uncompilable header.
func (w *headerWriter) orderRecords(records []*Declaration) []*Declaration {
	sorted := append([]*Declaration(nil), records...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	state := map[string]uint8{} // 1 visiting, 2 emitted, 3 failed
	var out []*Declaration
	var visit func(d *Declaration) bool
	visit = func(d *Declaration) bool {
		switch state[d.ID] {
		case 1:
			w.report(DiagCHeaderCycle, d, "`%s` is contained by value inside itself", d.Name)
			state[d.ID] = 3
			return false
		case 2:
			return true
		case 3:
			return false
		}
		state[d.ID] = 1
		for _, f := range d.Fields {
			dep, ok := w.valueRecord(f.Type, 0)
			if !ok || dep == nil {
				continue
			}
			if dep == d || !visit(dep) {
				if dep == d {
					w.report(DiagCHeaderCycle, d, "field `%s` makes `%s` contain itself by value", f.Name, d.Name)
				}
				state[d.ID] = 3
				return false
			}
		}
		state[d.ID] = 2
		out = append(out, d)
		return true
	}
	for _, d := range sorted {
		visit(d)
	}
	return out
}

// valueRecord resolves tr to the layout(C) record it carries by value, nil
// for anything else (a pointer, a scalar).
func (w *headerWriter) valueRecord(tr *TypeRef, depth int) (*Declaration, bool) {
	tr = w.resolve(tr, depth)
	if tr == nil {
		return nil, false
	}
	switch tr.Kind {
	case TRPrim, TRPointer, TRFn:
		return nil, tr.Kind != TRPrim || isCPrim(tr.Prim)
	case TRNamed:
		if tr.WellKnown == WKFixedArray && len(tr.Args) == 2 {
			return w.valueRecord(tr.Args[0], depth+1)
		}
		d := w.byID[declIDOf(tr)]
		if d == nil || d.Kind != KindType || d.Layout == "" {
			return nil, false
		}
		return d, true
	}
	return nil, false
}

// resolve follows a nominal defined type to its representation.
func (w *headerWriter) resolve(tr *TypeRef, depth int) *TypeRef {
	for depth < 32 && tr != nil && tr.Kind == TRNamed && tr.Decl != nil {
		d := w.byID[tr.Decl.ID]
		if d == nil || d.Form != "defined" || d.Underlying == nil {
			return tr
		}
		tr, depth = d.Underlying, depth+1
	}
	return tr
}

// typeName renders a type as a C specifier, for a return type.
func (w *headerWriter) typeName(tr *TypeRef, depth int) (string, bool) {
	tr = w.resolve(tr, depth)
	if tr == nil {
		return "", false
	}
	switch tr.Kind {
	case TRPrim:
		return w.prim(tr.Prim)
	case TRPointer:
		if tr.Elem == nil {
			return "void *", true
		}
		elem := w.resolve(tr.Elem, depth)
		if elem != nil && elem.Kind == TRFn {
			return "", false
		}
		base, ok := w.typeName(tr.Elem, depth)
		if !ok {
			return "", false
		}
		if !tr.Mutable && !strings.HasSuffix(base, "*") {
			base = "const " + base
		}
		if strings.HasSuffix(base, "*") {
			return base + "*", true
		}
		return base + " *", true
	case TRNamed:
		d := w.byID[declIDOf(tr)]
		if d == nil || d.Kind != KindType || d.Layout == "" {
			return "", false
		}
		return "struct " + d.Name, true
	}
	return "", false
}

// declType renders a C declaration of name with type tr: `int32_t x`,
// `const uint8_t *text`, `struct Point origin`, `uint8_t name[16]` or
// `int32_t (*fp)(void *)`.
func (w *headerWriter) declType(tr *TypeRef, name string, depth int) (string, bool) {
	if depth > 32 {
		return "", false
	}
	tr = w.resolve(tr, depth)
	if tr == nil {
		return "", false
	}
	switch tr.Kind {
	case TRPrim:
		base, ok := w.prim(tr.Prim)
		if !ok {
			return "", false
		}
		return base + " " + name, true
	case TRPointer:
		if tr.Elem == nil {
			return "void *" + name, true
		}
		elem := w.resolve(tr.Elem, depth)
		if elem != nil && elem.Kind == TRFn {
			return w.fnPointer(elem, name, depth)
		}
		inner, ok := w.declType(tr.Elem, "*"+name, depth+1)
		if !ok {
			return "", false
		}
		if !tr.Mutable && elem != nil && elem.Kind != TRPointer {
			inner = "const " + inner
		}
		return inner, true
	case TRNamed:
		if tr.WellKnown == WKFixedArray && len(tr.Args) == 2 {
			n := "0"
			if tr.Args[1] != nil && tr.Args[1].Value != "" {
				n = tr.Args[1].Value
			}
			return w.declType(tr.Args[0], name+"["+n+"]", depth+1)
		}
		d := w.byID[declIDOf(tr)]
		if d == nil || d.Kind != KindType || d.Layout == "" {
			return "", false
		}
		return "struct " + d.Name + " " + name, true
	}
	return "", false
}

// fnPointer renders a C function pointer: `ret (*name)(params)`.
func (w *headerWriter) fnPointer(tr *TypeRef, name string, depth int) (string, bool) {
	ret := "void"
	if tr.Elem != nil {
		text, ok := w.typeName(tr.Elem, depth+1)
		if !ok {
			return "", false
		}
		ret = text
	}
	var params []string
	for i, p := range tr.Params {
		text, ok := w.declType(p, "arg"+strconv.Itoa(i), depth+1)
		if !ok {
			return "", false
		}
		params = append(params, text)
	}
	if tr.Variadic {
		params = append(params, "...")
	}
	list := "(void)"
	if len(params) != 0 {
		list = "(" + strings.Join(params, ", ") + ")"
	}
	return fmt.Sprintf("%s (*%s)%s", ret, name, list), true
}

func (w *headerWriter) prim(name string) (string, bool) {
	switch name {
	case "Void", "Never":
		return "void", true
	case "Bool":
		w.usedBool = true
		return "bool", true
	case "Char":
		w.usedInt = true
		return "uint32_t", true
	case "usize":
		w.usedSize = true
		return "size_t", true
	case "isize":
		w.usedSize = true
		return "ptrdiff_t", true
	case "f32":
		return "float", true
	case "Float":
		return "double", true
	case "i8", "i16", "i32", "Int", "i128":
		w.usedInt = true
		if name == "i128" {
			return "__int128", true
		}
		return "int" + primWidth(name) + "_t", true
	case "u8", "u16", "u32", "u64", "u128":
		w.usedInt = true
		if name == "u128" {
			return "unsigned __int128", true
		}
		return "uint" + primWidth(name) + "_t", true
	}
	return "", false
}

func primWidth(name string) string {
	switch name {
	case "i8", "u8":
		return "8"
	case "i16", "u16":
		return "16"
	case "i32", "u32":
		return "32"
	}
	return "64"
}

func isCPrim(name string) bool {
	switch name {
	case "Void", "Never", "Bool", "Char", "usize", "isize", "f32", "Float",
		"i8", "i16", "i32", "Int", "i128", "u8", "u16", "u32", "u64", "u128":
		return true
	}
	return false
}

func declIDOf(tr *TypeRef) string {
	if tr == nil || tr.Decl == nil {
		return ""
	}
	return tr.Decl.ID
}

func displayOf(tr *TypeRef) string {
	if tr == nil {
		return "Void"
	}
	return tr.Display
}

func originComment(d *Declaration) string {
	kind := string(d.Kind)
	switch {
	case d.ABI != nil:
		kind = d.ABI.Block + "(" + d.ABI.Name + ")"
	case d.Kind == KindType && d.Opaque:
		kind = "opaque"
	case d.Kind == KindType && d.Layout != "":
		kind = "layout(" + d.Layout + ")"
	}
	return fmt.Sprintf("%s %s (%s:%d)", kind, d.ID, d.Origin.File, d.Origin.Line)
}

func defaultGuard(mod *Module) string {
	name := "KIGUMI"
	if len(mod.Envelope.Scope) != 0 && mod.Envelope.Scope[0] != "" {
		name = mod.Envelope.Scope[0]
	}
	var b strings.Builder
	b.WriteString("KIGUMI_")
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(unicode.ToUpper(r))
		} else {
			b.WriteByte('_')
		}
	}
	b.WriteString("_H")
	return b.String()
}

func isCIdent(name string) bool {
	if name == "" {
		return false
	}
	for i, r := range name {
		switch {
		case r == '_', unicode.IsLetter(r):
			continue
		case i > 0 && unicode.IsDigit(r):
			continue
		}
		return false
	}
	return true
}

func cKeyword(name string) bool {
	switch name {
	case "auto", "break", "case", "char", "const", "continue", "default", "do",
		"double", "else", "enum", "extern", "float", "for", "goto", "if",
		"inline", "int", "long", "register", "restrict", "return", "short",
		"signed", "sizeof", "static", "struct", "switch", "typedef", "union",
		"unsigned", "void", "volatile", "while", "_Bool", "_Alignas", "_Noreturn":
		return true
	}
	return false
}
